window.runUIScenarios=async()=>{
  const results=[];
  const ui=document.getElementById('feishu-original-tts').shadowRoot;
  const $=id=>ui.getElementById(id),d=()=>FeishuOriginalTTS.diagnostics();
  const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  function check(condition,label){if(!condition)throw new Error(label+' failed: '+JSON.stringify(globalThis.FeishuOriginalTTS?.diagnostics()||{}));results.push(label);}
  const seek=value=>{const e=$('seek');e.value=value;e.dispatchEvent(new Event('input'));e.dispatchEvent(new Event('change'));};
  try{
    check(d().scanCount===0&&!d().indexReady&&!d().scanning,'automatic player waits for first play before scanning');
    check(!$('close')&&!$('settings')&&$('voice').tagName==='SELECT','voice is a direct menu and close button is absent');
    check(getComputedStyle($('rate')).appearance==='base-select'&&getComputedStyle($('voice')).appearance==='base-select','both menus use browser top-layer pickers');
    $('play').click();await wait(2000);
    check(d().playing&&d().scanCount===1&&d().indexReady,'first play creates one cached index');
    const firstRequest=testBridge.messages.findLast(m=>m.type==='speak');
    const nextUncached=d().queue[firstRequest.ahead.length+1],buffered=firstRequest.ahead.reduce((sum,item)=>sum+FeishuTTSCore.characterCount(item.text),0),bufferTarget=FeishuTTSCore.lookaheadStats(d().queue).targetCharacters;
    check(firstRequest.ahead.length>0&&(!nextUncached||buffered>=Math.max(bufferTarget,FeishuTTSCore.characterCount(nextUncached.text)))&&firstRequest.ahead.every((item,i)=>item.text===d().queue[i+1].text),'lookahead cached text covers the statistical floor and next uncached sentence');
    $('play').click();check(d().paused,'main button pauses');
    $('play').click();check(d().playing&&!d().paused&&d().scanCount===1,'resume reuses scan');
    $('next').click();await wait(300);check(d().cursor===1&&d().scanCount===1,'next sentence keeps scan');
    $('prev').click();await wait(300);check(d().cursor===0&&d().scanCount===1,'previous sentence keeps scan');
    const target=Math.floor(d().total*.55);seek(target);await wait(400);
    check(d().playing&&Math.abs(d().absolute-target)<=1&&d().scanCount===1,'seek while playing jumps by full-document character');
    const before=d().absolute;testBridge.emit({type:'word',charIndex:2,length:2});
    check(d().absolute===before+2&&CSS.highlights.has('feishu-tts-word'),'word callback updates original text highlight and character progress');
    $('play').click();seek(Math.floor(d().total*.4));await wait(400);
    check(!d().playing&&d().scanCount===1,'seek while paused stays silent');
    $('play').click();await wait(300);check(d().playing&&d().scanCount===1,'play after seeking reuses scan');
    FeishuTTSLoader.sync();check(d().playing&&d().scanCount===1,'automatic loader does not remount an unchanged document');
    const scroller=document.querySelector('.bear-web-x-container');
    check($('follow').hidden&&d().following,'follow mode starts with return button hidden');
    scroller.dispatchEvent(new WheelEvent('wheel',{deltaY:300,bubbles:true}));
    scroller.scrollTop+=300;await wait(200);
    check(!d().following&&!$('follow').hidden,'manual wheel enters free browsing');
    const button=$('follow').getBoundingClientRect(),bar=ui.querySelector('.player').getBoundingClientRect();
    check(button.bottom<bar.top&&Math.abs((button.left+button.right)/2-innerWidth/2)<2&&!$('follow').closest('.player'),'return button floats above player and is horizontally centered');
    const fixedTop=scroller.scrollTop;
    testBridge.emit({type:'word',charIndex:1,length:2});await wait(200);
    check(scroller.scrollTop===fixedTop&&d().playing,'word updates do not scroll during free browsing');
    const key=d().current.key;
    const node=document.querySelector('.block[data-record-id="'+key+'"]'),parent=node.parentNode,next=node.nextSibling;
    node.remove();await wait(350);
    const absoluteBefore=d().absolute;
    testBridge.emit({type:'word',charIndex:3,length:2});await wait(100);
    check(d().playing&&d().indexReady&&d().absolute>absoluteBefore&&!CSS.highlights.has('feishu-tts-word'),'unrendered current paragraph keeps playing and updates cached progress');
    const cursorBefore=d().cursor;testBridge.emit({type:'end'});await wait(200);
    check(d().playing&&d().cursor===cursorBefore+1,'playback advances while paragraph is unrendered');
    const advanced=testBridge.messages.findLast(m=>m.type==='speak'),previous=testBridge.messages.filter(m=>m.type==='speak').at(-2);
    check(advanced.sessionId===previous.sessionId&&advanced.cacheKey===previous.ahead[0].cacheKey,'natural sentence transition reuses the prefetched sentence identity');
    parent.insertBefore(node,next);await wait(350);
    check(d().indexReady&&d().scanCount===1,'virtual remount keeps cache');
    $('follow').click();await wait(300);
    check(d().following&&$('follow').hidden,'return button restores follow and hides itself');
    const highlight=[...CSS.highlights.get('feishu-tts-sentence')][0].getClientRects()[0];
    const scrollBounds=scroller.getBoundingClientRect();
    check(Math.abs((highlight.top+highlight.bottom)/2-(scrollBounds.top+bar.top)/2)<3,'current playback is vertically centered in visible reading area');
    scroller.dispatchEvent(new PointerEvent('pointerdown',{clientX:scrollBounds.right-8,bubbles:true}));
    check(!d().following&&!$('follow').hidden,'overlay scrollbar drag enters free browsing');
    $('follow').click();
    // A real text change must invalidate, then rebuild on the next play.
    document.querySelector('[data-record-id="p17"] .text-editor').append('新增加的内容。');await wait(350);
    check(!d().indexReady&&!d().playing,'edited text invalidates cached index');
    $('play').click();await wait(2000);check(d().indexReady&&d().scanCount===2&&d().playing,'next play rebuilds after a content change');
    $('play').click();
    const zone=document.querySelector('[data-record-id="intro"] .text-editor'),range=document.createRange();
    range.setStart(zone.firstChild,1);range.setEnd(zone.firstChild,9);getSelection().removeAllRanges();getSelection().addRange(range);await wait(80);
    $('selection').click();await wait(400);
    check(d().playing&&d().current.text===zone.textContent.slice(1,9)&&d().scanCount===2,'selection-only playback retains cache and exact text');
    check(testBridge.messages.findLast(m=>m.type==='speak').ahead.length===0,'selection does not prefetch text outside selection');
    const player=document.getElementById('feishu-original-tts').getBoundingClientRect(),play=$('play').getBoundingClientRect();
    check(player.left===0&&Math.abs(player.right-innerWidth)<1&&Math.abs(player.bottom-innerHeight)<1,'player spans viewport bottom');
    check(Math.abs((play.left+play.right)/2-innerWidth/2)<4,'transport play button is centered');
    $('play').click();
    const cached={scans:d().scanCount,total:d().total,absolute:d().absolute};
    const originalRoot=document.querySelector('.root-block'),rootParent=originalRoot.parentNode;
    originalRoot.remove();await wait(850);
    check(!!document.getElementById('feishu-original-tts')&&d().scanCount===cached.scans&&d().indexReady,'temporary editor unmount retains player and cached text');
    rootParent.append(originalRoot);await wait(850);
    check(d().scanCount===cached.scans&&d().indexReady,'editor remount reuses the existing reader');
    return{ok:true,results,final:{scans:d().scanCount,total:d().total,absolute:d().absolute}};
  }catch(error){return{ok:false,results,error:error.stack};}
};
